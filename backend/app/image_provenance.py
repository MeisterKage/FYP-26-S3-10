"""Does an uploaded image say it was made by AI?

AI-generated images are not allowed on the site. This finds the ones that
declare it, which is most of what the big generators produce:

  * the IPTC "digital source type" that C2PA content credentials and Adobe,
    Google, OpenAI and Microsoft write into generated images
    (trainedAlgorithmicMedia, and compositeWithTrainedAlgorithmicMedia for an
    edit such as generative fill);
  * a generator named in the metadata (Midjourney, DALL-E, Stable Diffusion,
    Firefly and others);
  * the generation settings Stable Diffusion tools save as text in a PNG.

Only the file's metadata sections are read (EXIF, XMP, IPTC, C2PA, PNG text,
comments), never the compressed pixel data, so a chance byte pattern in a
photograph cannot trip it.

What it cannot do: tell from the pixels alone that an image was generated.
An image with its metadata stripped (a screenshot, or one re-saved by some
apps) passes. That is why writers also confirm, when they upload, that an
image is not AI-generated, and why the editor checks the image on review.
"""
from __future__ import annotations

import re
import struct

#: (pattern, what to tell the writer). Checked against lower-cased metadata.
MARKERS: tuple[tuple[str, str], ...] = (
    (r"trainedalgorithmicmedia", "its content credentials record it as AI-generated"),
    (r"midjourney", "it was made with Midjourney"),
    (r"dall[-·· ]?e\b|\bdalle\b", "it was made with DALL-E"),
    (r"stable[ -]?diffusion|\bsdxl\b", "it was made with Stable Diffusion"),
    (r"adobe firefly|\bfirefly\b", "it was made or edited with Adobe Firefly"),
    (r"\bideogram\b", "it was made with Ideogram"),
    (r"leonardo\.ai", "it was made with Leonardo.Ai"),
    (r"\bnovelai\b", "it was made with NovelAI"),
    (r"\bcomfyui\b", "it was made with ComfyUI"),
    (r"automatic1111|\binvokeai\b", "it was made with a Stable Diffusion tool"),
    (r"bing image creator|microsoft designer|image creator from microsoft", "it was made with Microsoft's image creator"),
    (r"\bopenai\b|\bchatgpt\b|gpt-4o|gpt-image", "it was made with OpenAI's image tools"),
    (r"google gemini|\bimagen [0-9]|synthid", "it was made with Google's image tools"),
    (r"flux\.1|black forest labs", "it was made with FLUX"),
    (r"\bcraiyon\b|dreamstudio|nightcafe|playground ai", "it was made with an AI image generator"),
    (r"cfg scale:|sampler: |negative prompt:", "it carries AI image-generation settings"),
    (r"\bai[- ]generated\b|generated by ai|made with ai", "its metadata says it is AI-generated"),
)


def _jpeg_metadata(data: bytes) -> list[bytes]:
    out, i = [], 2
    while i + 4 <= len(data) and data[i] == 0xFF:
        marker = data[i + 1]
        if marker == 0xDA:  #start of scan: pixel data follows
            break
        if marker in (0xD8, 0x01) or 0xD0 <= marker <= 0xD7:
            i += 2
            continue
        length = struct.unpack(">H", data[i + 2:i + 4])[0]
        if 0xE0 <= marker <= 0xEF or marker == 0xFE:  #APPn and comments
            out.append(data[i + 4:i + 2 + length])
        i += 2 + length
    return out


def _png_metadata(data: bytes) -> list[bytes]:
    out, i = [], 8
    skip = {b"IDAT", b"IHDR", b"PLTE", b"IEND"}
    while i + 8 <= len(data):
        length = struct.unpack(">I", data[i:i + 4])[0]
        kind = data[i + 4:i + 8]
        if kind not in skip:
            out.append(kind + data[i + 8:i + 8 + length])
        i += 12 + length
        if kind == b"IEND":
            break
    return out


def _webp_metadata(data: bytes) -> list[bytes]:
    out, i = [], 12
    skip = {b"VP8 ", b"VP8L", b"VP8X", b"ANIM", b"ANMF", b"ALPH"}
    while i + 8 <= len(data):
        kind = data[i:i + 4]
        length = struct.unpack("<I", data[i + 4:i + 8])[0]
        if kind not in skip:
            out.append(kind + data[i + 8:i + 8 + length])
        i += 8 + length + (length & 1)
    return out


def metadata_text(data: bytes) -> str:
    """Every metadata section of a JPEG, PNG or WebP, as searchable text."""
    if data[:2] == b"\xff\xd8":
        parts = _jpeg_metadata(data)
    elif data[:8] == b"\x89PNG\r\n\x1a\n":
        parts = _png_metadata(data)
    elif data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        parts = _webp_metadata(data)
    else:
        parts = []
    text = []
    for part in parts:
        text.append(part.decode("latin-1"))
        #EXIF UserComment and some XMP are UTF-16.
        text.append(part.decode("utf-16-le", errors="ignore"))
        if part[:4] == b"zTXt" or part[:4] == b"iTXt":
            text.append(_inflate_text(part))
    return "\n".join(text).lower()


def _inflate_text(part: bytes) -> str:
    """Compressed PNG text chunks (zTXt, compressed iTXt), decoded."""
    import zlib

    body = part[4:]
    try:
        if part[:4] == b"zTXt":
            key, _, rest = body.partition(b"\x00")
            return zlib.decompress(rest[1:]).decode("utf-8", errors="ignore")
        key, _, rest = body.partition(b"\x00")
        compressed = rest[:1] == b"\x01"
        rest = rest[2:]
        _, _, rest = rest.partition(b"\x00")  #language tag
        _, _, rest = rest.partition(b"\x00")  #translated keyword
        return (zlib.decompress(rest) if compressed else rest).decode("utf-8", errors="ignore")
    except (zlib.error, ValueError):
        return ""


def ai_markers(data: bytes) -> list[str]:
    """Why this image looks AI-generated, from its own metadata. Empty if no sign."""
    text = metadata_text(data)
    if not text:
        return []
    found = []
    for pattern, reason in MARKERS:
        if re.search(pattern, text) and reason not in found:
            found.append(reason)
    return found
